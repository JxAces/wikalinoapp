type WardrobeResult = { correct?: boolean; wardrobeDressed?: boolean; wardrobePieces?: number[] };

export function isWardrobeDressed(result?: WardrobeResult): boolean {
  if (!result?.correct) return false;
  if (typeof result.wardrobeDressed === "boolean") return result.wardrobeDressed;
  // Keep completed compass and four-piece outfits; partial outfits await one whole garment.
  return result.wardrobePieces === undefined || [0, 1, 2, 3].every(part => result.wardrobePieces?.includes(part));
}

export function needsWardrobeDressing(result?: WardrobeResult) {
  return result?.correct === true && !isWardrobeDressed(result);
}
